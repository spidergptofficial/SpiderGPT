import 'dotenv/config';
import 'express-async-errors';
import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import { config, validateConfig } from './config.js';
import { log } from './log.js';
import { errorHandler } from './errors.js';
import { authRouter, requireAuth, csrfGuard } from './auth.js';
import { api, handleRazorpayWebhook, handleStripeWebhook } from './routes.js';
validateConfig();
const app=express();app.set('trust proxy',1);
app.use(helmet({crossOriginResourcePolicy:{policy:'cross-origin'}}));
app.use(cors({origin:config.webOrigin,credentials:true,methods:['GET','POST','PUT','PATCH','DELETE','OPTIONS'],allowedHeaders:['content-type','x-requested-with']}));
app.use('/webhooks/razorpay',express.raw({type:'application/json',limit:'1mb'}),(req,res,next)=>{req.rawBody=req.body;try{req.body=JSON.parse(req.body.toString('utf8'));}catch{return res.status(400).json({ok:false});}next();},handleRazorpayWebhook);
app.use('/webhooks/stripe',express.raw({type:'application/json',limit:'1mb'}),(req,res,next)=>{req.rawBody=req.body;try{req.body=JSON.parse(req.body.toString('utf8'));}catch{return res.status(400).json({ok:false});}next();},handleStripeWebhook);
app.use(express.json({limit:'64kb'}),cookieParser(),csrfGuard);
app.get('/health',async(_req,res)=>{res.json({ok:true,service:'spidergpt-api',time:new Date().toISOString()});});
app.get('/health/db',async(_req,res)=>{const {db}=await import('./db.js');await db.query('SELECT 1');res.json({ok:true});});
app.use('/auth',authRouter);app.use('/api',requireAuth,api);app.use(errorHandler(log));
app.listen(config.port,()=>log.info({port:config.port,env:config.nodeEnv},'SpiderGPT API up'));
